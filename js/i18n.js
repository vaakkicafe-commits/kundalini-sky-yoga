window.currentLang = localStorage.getItem("sky_lang") || "en";

window.setLanguage = function(lang) {
  window.currentLang = lang;
  localStorage.setItem("sky_lang", lang);

  // Update static elements with data-i18n
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (window.translations[lang] && window.translations[lang][key]) {
      el.textContent = window.translations[lang][key];
    }
  });

  // Toggle active button style
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active-lang", btn.dataset.lang === lang);
  });

  // Trigger dynamic component re-renders
  if (typeof renderChakraDetails === "function") renderChakraDetails();
  if (typeof renderAsanaCarousel === "function") renderAsanaCarousel();
  if (typeof renderScientificTabs === "function") {
    renderScientificTabs();
    renderScientificCard();
  }
  if (typeof renderCourses === "function") {
    const activeTab = document.querySelector('.tab-btn.active');
    renderCourses(activeTab ? activeTab.dataset.category : 'all');
  }
  if (typeof renderPublications === "function") renderPublications();
  if (typeof updatePromptDisplay === "function") updatePromptDisplay();
  if (typeof updateQuoteDisplay === "function") updateQuoteDisplay();
};

document.addEventListener("DOMContentLoaded", () => {
  window.setLanguage(window.currentLang);
});
